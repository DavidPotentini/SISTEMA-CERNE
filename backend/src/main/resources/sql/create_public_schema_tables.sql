CREATE TYPE VLD_STATUS_INCUBADORA AS ENUM ('EM_OPERACAO', 'AGUARDANDO_ATIVACAO', 'SUSPENSA');
CREATE TYPE VLD_STATUS_CONTA      AS ENUM ('ATIVO', 'CONVIDADO', 'SUSPENSO');
CREATE TYPE VLD_NIVEL_INCUBADORA  AS ENUM ('CERNE 1');

-- Identidade de login única de todos (admin da plataforma + pessoas de incubadora).
CREATE TABLE IF NOT EXISTS CONTAS (
    CTA_COD          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME             TEXT NOT NULL,
    EMAIL            VARCHAR(255) UNIQUE NOT NULL,
    SENHA            TEXT NOT NULL,                       -- hash BCrypt
    STATUS           VLD_STATUS_CONTA NOT NULL DEFAULT 'CONVIDADO',
    ADMIN_PLATAFORMA BOOLEAN NOT NULL DEFAULT FALSE,      -- TRUE = administrador da plataforma
    INC_COD          BIGINT   -- incubadora da conta (1:1); NULL p/ admin. FK add. após INCUBADORAS
);

-- Incubadora = também é o registro de tenant (NOME_SCHEMA).
CREATE TABLE IF NOT EXISTS INCUBADORAS (
    INC_COD       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME          TEXT NOT NULL,
    CNPJ          VARCHAR(14) UNIQUE,
    MANTENEDORA   TEXT,
    RESP_CTA_COD  BIGINT REFERENCES CONTAS(CTA_COD),    -- responsável → conta (FK real, mesmo schema)
    EMAIL         TEXT,
    TELEFONE      TEXT,
    CIDADE        TEXT,
    NIVEL         VLD_NIVEL_INCUBADORA,
    STATUS        VLD_STATUS_INCUBADORA NOT NULL DEFAULT 'AGUARDANDO_ATIVACAO',
    NOME_SCHEMA   VARCHAR(63) UNIQUE NOT NULL,          -- schema Postgres do tenant
    CRIADA_EM     TIMESTAMP DEFAULT NOW(),
    ATIVADA_EM    TIMESTAMP
);

ALTER TABLE CONTAS ADD CONSTRAINT FK_INCUBADORA FOREIGN KEY (INC_COD) REFERENCES INCUBADORAS (INC_COD);